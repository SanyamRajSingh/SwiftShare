-- 3. CRUD Operations - UPDATE
UPDATE demo_transfers
SET status = 'Success (Verified)'
WHERE transfer_id = 1;

-- 4. Filtering and Logical Operators (WHERE, AND, OR, LIKE, BETWEEN)
SELECT * FROM demo_transfers
WHERE filesize_bytes BETWEEN 1000000 AND 6000000
  AND status LIKE 'Success%';

-- 5. Relational JOINs (INNER JOIN, LEFT JOIN, Multi-Table JOIN)
SELECT 
    t.transfer_id,
    t.filename,
    t.filesize_bytes,
    s.hostname AS sender_host,
    s.ip_address AS sender_ip,
    r.hostname AS receiver_host,
    r.ip_address AS receiver_ip,
    t.status
FROM demo_transfers t
INNER JOIN demo_peers s ON t.sender_peer_id = s.peer_id
INNER JOIN demo_peers r ON t.receiver_peer_id = r.peer_id
ORDER BY t.filesize_bytes DESC;

-- LEFT JOIN with Aggregate Calculation
SELECT 
    p.hostname,
    p.ip_address,
    COUNT(t.transfer_id) AS total_sent_transfers,
    COALESCE(SUM(t.filesize_bytes), 0) AS total_sent_bytes
FROM demo_peers p
LEFT JOIN demo_transfers t ON p.peer_id = t.sender_peer_id
GROUP BY p.peer_id, p.hostname, p.ip_address
HAVING COUNT(t.transfer_id) >= 0
ORDER BY total_sent_bytes DESC;

-- 6. Subqueries (Scalar subquery & Correlated subquery)
-- Transfers larger than the overall average file size
SELECT transfer_id, filename, filesize_bytes, status
FROM demo_transfers
WHERE filesize_bytes > (SELECT AVG(filesize_bytes) FROM demo_transfers);

-- 7. Set Operations: UNION
-- Peers who participated as either sender OR receiver
SELECT ip_address, hostname FROM demo_peers WHERE peer_id IN (SELECT sender_peer_id FROM demo_transfers)
UNION
SELECT ip_address, hostname FROM demo_peers WHERE peer_id IN (SELECT receiver_peer_id FROM demo_transfers);

-- 8. Set Operations: INTERSECT
-- Peers who have acted as BOTH sender AND receiver
SELECT sender_peer_id AS peer_id FROM demo_transfers
INTERSECT
SELECT receiver_peer_id AS peer_id FROM demo_transfers;

-- 9. Set Operations: EXCEPT
-- Peers who have sent files but NEVER received a file
SELECT sender_peer_id AS peer_id FROM demo_transfers
EXCEPT
SELECT receiver_peer_id AS peer_id FROM demo_transfers;

