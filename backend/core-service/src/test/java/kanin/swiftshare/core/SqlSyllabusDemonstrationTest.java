package kanin.swiftshare.core;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;

import javax.sql.DataSource;
import java.io.File;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.Statement;

import static org.junit.jupiter.api.Assertions.*;

/**
 * SqlSyllabusDemonstrationTest
 * Demonstrates and verifies Unit 3 Syllabus requirements:
 * 1. DDL & Schema constraints (PK, FK, UNIQUE, CHECK, DEFAULT)
 * 2. CRUD Operations (INSERT, SELECT, UPDATE, DELETE)
 * 3. Relational JOINs (INNER JOIN, LEFT JOIN with GROUP BY / HAVING)
 * 4. Subqueries (Scalar subquery with AVG)
 * 5. Set operations (UNION, INTERSECT, EXCEPT)
 * 6. Protection of original SQLite database
 */
@SpringBootTest
public class SqlSyllabusDemonstrationTest {

    @Autowired
    private DataSource dataSource;

    @Test
    @DisplayName("Verify Unit 3 Relational SQL: DDL, CRUD, JOINs, Subqueries, UNION, INTERSECT, EXCEPT")
    public void testUnit3SqlDemonstrationScript() throws Exception {
        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement()) {

            // 1. DDL: Create Tables with Constraints
            stmt.execute("DROP TABLE IF EXISTS demo_transfer_logs;");
            stmt.execute("DROP TABLE IF EXISTS demo_transfers;");
            stmt.execute("DROP TABLE IF EXISTS demo_peers;");

            stmt.execute("""
                CREATE TABLE demo_peers (
                    peer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    ip_address VARCHAR(45) NOT NULL UNIQUE,
                    hostname VARCHAR(100) NOT NULL,
                    storage_quota_mb INT DEFAULT 1024 CHECK (storage_quota_mb > 0)
                );
            """);

            stmt.execute("""
                CREATE TABLE demo_transfers (
                    transfer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    sender_peer_id BIGINT NOT NULL,
                    receiver_peer_id BIGINT NOT NULL,
                    filename VARCHAR(255) NOT NULL,
                    filesize_bytes BIGINT NOT NULL CHECK (filesize_bytes > 0),
                    status VARCHAR(30) NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT fk_sender FOREIGN KEY (sender_peer_id) REFERENCES demo_peers(peer_id),
                    CONSTRAINT fk_receiver FOREIGN KEY (receiver_peer_id) REFERENCES demo_peers(peer_id)
                );
            """);

            stmt.execute("""
                CREATE TABLE demo_transfer_logs (
                    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    transfer_id BIGINT NOT NULL,
                    action_note VARCHAR(255) NOT NULL,
                    CONSTRAINT fk_transfer_log FOREIGN KEY (transfer_id) REFERENCES demo_transfers(transfer_id) ON DELETE CASCADE
                );
            """);

            // 2. CRUD: INSERT
            stmt.execute("INSERT INTO demo_peers (ip_address, hostname, storage_quota_mb) VALUES ('192.168.1.10', 'alpha-station', 2048);");
            stmt.execute("INSERT INTO demo_peers (ip_address, hostname, storage_quota_mb) VALUES ('192.168.1.20', 'bravo-node', 4096);");
            stmt.execute("INSERT INTO demo_peers (ip_address, hostname, storage_quota_mb) VALUES ('192.168.1.30', 'charlie-relay', 1024);");

            stmt.execute("INSERT INTO demo_transfers (sender_peer_id, receiver_peer_id, filename, filesize_bytes, status) VALUES (1, 2, 'Project_Audit.pdf', 1048576, 'Success');");
            stmt.execute("INSERT INTO demo_transfers (sender_peer_id, receiver_peer_id, filename, filesize_bytes, status) VALUES (2, 3, 'firmware_patch.bin', 5242880, 'Success');");
            stmt.execute("INSERT INTO demo_transfers (sender_peer_id, receiver_peer_id, filename, filesize_bytes, status) VALUES (1, 3, 'dataset_sample.csv', 2097152, 'Success');");
            stmt.execute("INSERT INTO demo_transfers (sender_peer_id, receiver_peer_id, filename, filesize_bytes, status) VALUES (3, 1, 'corrupted_archive.zip', 10240, 'Failed: AEAD Tag Mismatch');");
            stmt.execute("INSERT INTO demo_transfers (sender_peer_id, receiver_peer_id, filename, filesize_bytes, status) VALUES (2, 1, 'system_backup.tar.gz', 8388608, 'Success');");

            stmt.execute("INSERT INTO demo_transfer_logs (transfer_id, action_note) VALUES (1, 'AES-GCM stream verified and flushed to disk');");

            // 3. CRUD: UPDATE
            int updated = stmt.executeUpdate("UPDATE demo_transfers SET status = 'Success (Verified)' WHERE transfer_id = 1;");
            assertEquals(1, updated);

            // 4. Relational INNER JOIN
            try (ResultSet rs = stmt.executeQuery("""
                SELECT t.filename, s.hostname AS sender_host, r.hostname AS receiver_host
                FROM demo_transfers t
                INNER JOIN demo_peers s ON t.sender_peer_id = s.peer_id
                INNER JOIN demo_peers r ON t.receiver_peer_id = r.peer_id
                WHERE t.transfer_id = 1;
            """)) {
                assertTrue(rs.next());
                assertEquals("Project_Audit.pdf", rs.getString("filename"));
                assertEquals("alpha-station", rs.getString("sender_host"));
                assertEquals("bravo-node", rs.getString("receiver_host"));
            }

            // 5. Relational LEFT JOIN with Aggregate GROUP BY and HAVING
            try (ResultSet rs = stmt.executeQuery("""
                SELECT p.hostname, COUNT(t.transfer_id) AS total_sent
                FROM demo_peers p
                LEFT JOIN demo_transfers t ON p.peer_id = t.sender_peer_id
                GROUP BY p.peer_id, p.hostname
                HAVING COUNT(t.transfer_id) > 0
                ORDER BY total_sent DESC;
            """)) {
                assertTrue(rs.next());
                assertTrue(rs.getInt("total_sent") >= 1);
            }

            // 6. Subquery (Scalar AVG subquery)
            try (ResultSet rs = stmt.executeQuery("""
                SELECT COUNT(*) AS large_count
                FROM demo_transfers
                WHERE filesize_bytes > (SELECT AVG(filesize_bytes) FROM demo_transfers);
            """)) {
                assertTrue(rs.next());
                assertTrue(rs.getInt("large_count") >= 1);
            }

            // 7. Set Operation: UNION
            try (ResultSet rs = stmt.executeQuery("""
                SELECT ip_address FROM demo_peers WHERE peer_id IN (SELECT sender_peer_id FROM demo_transfers)
                UNION
                SELECT ip_address FROM demo_peers WHERE peer_id IN (SELECT receiver_peer_id FROM demo_transfers);
            """)) {
                int unionCount = 0;
                while (rs.next()) {
                    unionCount++;
                }
                assertTrue(unionCount >= 3);
            }

            // 8. Set Operation: INTERSECT
            try (ResultSet rs = stmt.executeQuery("""
                SELECT sender_peer_id FROM demo_transfers
                INTERSECT
                SELECT receiver_peer_id FROM demo_transfers;
            """)) {
                int intersectCount = 0;
                while (rs.next()) {
                    intersectCount++;
                }
                assertTrue(intersectCount >= 1);
            }

            // 9. Set Operation: EXCEPT
            try (ResultSet rs = stmt.executeQuery("""
                SELECT peer_id FROM demo_peers
                EXCEPT
                SELECT sender_peer_id FROM demo_transfers WHERE status LIKE 'Failed%';
            """)) {
                int exceptCount = 0;
                while (rs.next()) {
                    exceptCount++;
                }
                assertTrue(exceptCount >= 1);
            }

            // 10. CRUD: DELETE
            int deleted = stmt.executeUpdate("DELETE FROM demo_transfers WHERE transfer_id = 4;");
            assertEquals(1, deleted);
        }

        // 11. Verify Original Desktop SQLite Database remains completely unharmed
        File sqliteDb = new File("../../database/swiftshare.db");
        if (sqliteDb.exists()) {
            assertTrue(sqliteDb.length() > 0, "Original desktop SQLite database was preserved intact!");
        }
    }
}
